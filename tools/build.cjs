// Build self-contained client artifacts from one set of data + one algorithm.
const fs = require('node:fs');
const path = require('node:path');
const yaml = require('js-yaml');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const data = {
  defaults: yaml.load(read('core/dns.yaml')),
  rules: JSON.parse(read('core/direct-rules.json')),
  providers: JSON.parse(read('core/providers.json'))
};
const engine = `const HMXX_DATA = ${JSON.stringify(data, null, 2)};\n\n${read('core/transform.js')}`;
const script = applyDns => engine + `\nfunction main(config) {\n  return hmxxTransform(config, { applyDns: ${applyDns} });\n}\n`;
const banner = '// Generated by tools/build.cjs. Edit core/ instead, then rebuild.\n';
const portable = banner + script(true);
const parser = fs.readFileSync(require.resolve('js-yaml/browser'), 'utf8');
const license = read('node_modules/js-yaml/LICENSE');
const browser = read('tools/portable.template.html')
  .replace('<!-- BUNDLED_SCRIPTS -->', () => `<script>/* ${license} */
${parser.replace(/<\/script/gi, '<\\/script')}</script>\n<script>${portable}</script>\n<script>${read('tools/compose-browser.js')}</script>`);
const outputs = {
  'global-merge.yaml': '# Generated from core/dns.yaml. GLOBAL Merge, paired with global-script.js.\n' + read('core/dns.yaml'),
  'global-script.js': banner + script(false),
  'adapters/flclash.js': '// FlClash profile script: main(config), no separate Merge required.\n' + portable,
  'adapters/clashmi.js': '// Clash Mi JS profile patch: main(config). Client settings can override it.\n' + portable,
  'adapters/portable.js': portable + '\nif (typeof module !== "undefined") module.exports = main;\n',
  'tools/portable.html': browser,
  'tools/THIRD-PARTY-NOTICES.txt': 'portable.html bundles js-yaml 5.4.3 (https://github.com/nodeca/js-yaml).\n\n' + license
};
for (const [file, content] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(path.join(root, file)) || read(file) !== content) throw new Error('Generated artifact out of date: '+file);
  } else {
    fs.writeFileSync(path.join(root, file), content);
  }
}
console.log(process.argv.includes('--check') ? 'Generated artifacts match core sources.' : 'Generated client artifacts.');
